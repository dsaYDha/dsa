/** 대사 하나 고르기 + 치환 */
export function dline(kind, vars = {}) {
  const list = DLINES[kind];
  let s = R.pick(list);
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export function numWord(n) {
  return NUM_WORDS[n] ?? String(n);
}
